def ensure_catalog_translations(conn: Connection) -> dict[str, int]:
    services = 0
    categories = 0
    for slug, translations in SERVICES.items():
        for language_code, (name, description) in translations.items():
            result = conn.execute(
                text(
                    """
                    INSERT INTO service_translations (
                      service_id, language_code, name, short_description, full_description
                    )
                    SELECT id, :lang, :name, :description, :description
                    FROM services WHERE slug = :slug
                    ON CONFLICT (service_id, language_code) DO UPDATE SET
                      name = EXCLUDED.name,
                      short_description = EXCLUDED.short_description,
                      full_description = EXCLUDED.full_description,
                      updated_at = NOW()
                    """
                ),
                {"slug": slug, "lang": language_code, "name": name, "description": description},
            )
            services += max(0, result.rowcount or 0)

    for slug, translations in CATEGORIES.items():
        for language_code, name in translations.items():
            result = conn.execute(
                text(
                    """
                    INSERT INTO category_translations (category_id, language_code, name)
                    SELECT id, :lang, :name FROM service_categories WHERE slug = :slug
                    ON CONFLICT (category_id, language_code) DO UPDATE SET
                      name = EXCLUDED.name, updated_at = NOW()
                    """
                ),
                {"slug": slug, "lang": language_code, "name": name},
            )
            categories += max(0, result.rowcount or 0)
    return {"services": services, "categories": categories}
