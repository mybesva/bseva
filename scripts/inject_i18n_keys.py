MARKER = "  \"mobile.notificationsWhy\":"


def inject(lang: str) -> None:
    path = ROOT / f"{lang}.ts"
    text = path.read_text()
    extra = KEYS[lang]
    lines = []
    for k, v in extra.items():
        if f'"{k}":' in text:
            continue
        esc = v.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  "{k}": "{esc}",')
    if not lines:
        print(f"{lang}: already present")
        return
    block = "\n".join(lines) + "\n"
    if MARKER not in text:
        raise SystemExit(f"marker missing in {lang}")
    # insert after the notificationsWhy line
    idx = text.find(MARKER)
    end = text.find("\n", idx)
